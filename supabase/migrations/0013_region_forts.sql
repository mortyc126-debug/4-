-- =============================================================================
-- Фаза 50 — крепости варваров: по одной в каждом из шестнадцати регионов.
-- =============================================================================
-- Автор: «в новой игре, то есть при старте сервера, в каждом регионе
-- располагается форт варваров (их три уровня по сложности). Каждый из них
-- должен быть уничтожен альянсом, чтобы захватить регион».
--
-- Эта миграция только СТАВИТ их на карту. Захват, постройка альянсовой
-- крепости на освободившемся месте и возврат варваров через 12 часов — всё
-- это следующим шагом; здесь заводится место, которое всё то будет менять.
--
-- ГДЕ СТОЯТ. Координаты посчитаны tools/gen_region_forts.mjs и вставлены
-- сюда как есть — руками их не правят. Исходная точка каждой крепости —
-- capital_world из worldgen/regions/regions_meta.json (generate_regions.py
-- выбирал её не в голом центре региона, а как место под крепость). Три
-- столицы из шестнадцати не прошли проверку самой игры — стояли на круче
-- (перепад больше STEEP_MAX_RISE, тот же порог, по которому index.html
-- отказывается ставить туда лагерь), — и сдвинуты к ближайшей ровной клетке
-- в своём же регионе, на 2-3 клетки. Вода и чужой регион проверены у всех
-- шестнадцати.
--
-- ПОЧЕМУ В map_cells, А НЕ В СВОЕЙ ТАБЛИЦЕ. Крепость — это объект на клетке
-- мира, ровно как узел сбора и лагерь варваров (миграция 0001). В map_cells
-- она достаётся клиенту тем же запросом, что и они (mpRefreshCamps), рисуется
-- тем же слоем и становится целью марша тем же путём. Отдельная таблица
-- означала бы вторую выборку, второй слой на карте и второй разбор в mp-tick
-- ради шестнадцати строк. Владение регионом при этом живёт не здесь, а в
-- data.alliance_id — см. ниже.
--
-- Как применить: Supabase Dashboard -> SQL Editor -> вставить целиком -> Run.

-- ---------------------------------------------------------------------------
-- Сеятель. Функцией, а не разовым INSERT'ом, по двум причинам: во-первых,
-- миры могут появиться позже (worlds заведена «на будущее» ещё в 0001, и
-- mp-join создаёт мир, если его нет) — тогда крепости ставит одна строка
-- вызова, а не копия шестнадцати координат в edge-функции; во-вторых, так
-- она перезапускаема: накатили миграцию дважды — ничего не задвоилось.
--
-- Идемпотентность: уже стоящую крепость НЕ ТРОГАЕМ (on conflict do nothing по
-- ключу map_cells). Это важно не для повторного наката, а для будущего: когда
-- крепость возьмут и на её месте встанет альянсовая, повторный вызов не
-- должен вернуть варваров на место.
create or replace function seed_region_forts(p_world uuid)
returns int language plpgsql as $$
declare
  n int := 0;
begin
  -- Место под крепость расчищается: узел сбора или лагерь варваров на той же
  -- клетке уступает. Они возрождаются сами (см. applyNodeRespawn/
  -- applyCampRespawn в mp-tick), а крепость региона — одна на весь мир и
  -- сдвинуться никуда не может.
  delete from map_cells c
   using (values
    ( 1, 1,  -844,  -385, 'Северное Побережье', 'Соляная Пристань'),
    ( 2, 1,   -91,  -396, 'Северные Поля', 'Хлебный Алтарь'),
    ( 3, 2,   326,  -448, 'Ледяные Пики', 'Ледяной Дозор'),
    ( 4, 1,   803,  -398, 'Торговая Бухта', 'Гостиный Двор'),
    ( 5, 1,  -883,   -46, 'Западная Пустошь', 'Ветряной Стан'),
    ( 6, 3,  -402,  -226, 'Зелёные Земли', 'Житница Предвечных'),
    ( 7, 3,   227,  -161, 'Великая Степь', 'Ханская Ставка'),
    ( 8, 1,   974,   -41, 'Восточная Гавань', 'Корабельная Роща'),
    ( 9, 2,  -547,   136, 'Древний Лес', 'Тайная Тропа'),
    (10, 3,   -71,   158, 'Открытые Равнины', 'Курган Павших'),
    (11, 2,   318,   189, 'Богатая Долина', 'Рог Изобилия'),
    (12, 3,   661,    19, 'Стальные Горы', 'Кузнечный Кряж'),
    (13, 1,  -852,   384, 'Южный Берег', 'Маячный Утёс'),
    (14, 2,  -305,   416, 'Гранитный Кряж', 'Каменный Венец'),
    (15, 2,   305,   463, 'Тёмная Чаща', 'Лучный Схрон'),
    (16, 2,   855,   375, 'Грозовые Вершины', 'Янтарный Престол')
   ) as f(region, tier, x, y, region_name, shrine)
   where c.world_id = p_world and c.x = f.x and c.y = f.y and c.t <> 'regfort';

  with f(region, tier, x, y, region_name, shrine) as (values
    ( 1, 1,  -844,  -385, 'Северное Побережье', 'Соляная Пристань'),
    ( 2, 1,   -91,  -396, 'Северные Поля', 'Хлебный Алтарь'),
    ( 3, 2,   326,  -448, 'Ледяные Пики', 'Ледяной Дозор'),
    ( 4, 1,   803,  -398, 'Торговая Бухта', 'Гостиный Двор'),
    ( 5, 1,  -883,   -46, 'Западная Пустошь', 'Ветряной Стан'),
    ( 6, 3,  -402,  -226, 'Зелёные Земли', 'Житница Предвечных'),
    ( 7, 3,   227,  -161, 'Великая Степь', 'Ханская Ставка'),
    ( 8, 1,   974,   -41, 'Восточная Гавань', 'Корабельная Роща'),
    ( 9, 2,  -547,   136, 'Древний Лес', 'Тайная Тропа'),
    (10, 3,   -71,   158, 'Открытые Равнины', 'Курган Павших'),
    (11, 2,   318,   189, 'Богатая Долина', 'Рог Изобилия'),
    (12, 3,   661,    19, 'Стальные Горы', 'Кузнечный Кряж'),
    (13, 1,  -852,   384, 'Южный Берег', 'Маячный Утёс'),
    (14, 2,  -305,   416, 'Гранитный Кряж', 'Каменный Венец'),
    (15, 2,   305,   463, 'Тёмная Чаща', 'Лучный Схрон'),
    (16, 2,   855,   375, 'Грозовые Вершины', 'Янтарный Престол')
  )
  insert into map_cells (world_id, x, y, t, data)
  select p_world, f.x, f.y, 'regfort',
         jsonb_build_object(
           -- Кто это и где. region — тот же номер, что в regions_meta.json
           -- (и на единицу больше значения в regions-v1.bin, см. REGION_NAMES
           -- в index.html).
           'region', f.region,
           'region_name', f.region_name,
           'shrine', f.shrine,
           -- Ступень сложности: 3 — великая твердыня (шесть соседей у
           -- региона), 2 — средняя, 1 — малая. Она же выбирает модель на
           -- карте (models/forts/barbarian-<tier>.glb).
           -- УРОВНЯ У КРЕПОСТИ НЕТ, в отличие от лагерей: «они не как лагеря
           -- варваров, это нечто уникальное, как святыня» (слова автора).
           'tier', f.tier,
           -- Чья и что с ней. 'barb' — стоит крепость варваров; дальше будут
           -- 'razed' (снесена, место свободно под альянсовую) и 'ally'
           -- (стоит альянсовая). Заводим все три сразу, чтобы следующий шаг
           -- не переписывал уже посеянные строки.
           'state', 'barb',
           'alliance_id', null,
           -- Когда снесли крепость варваров: от этой метки идут двенадцать
           -- часов, после которых они возвращаются, если альянс не построил
           -- свою (прямое условие автора).
           'razed_at', null
         )
  from f
  on conflict (world_id, x, y) do nothing;
  get diagnostics n = row_count;
  return n;
end $$;

-- ---------------------------------------------------------------------------
-- Ставим во все уже существующие миры (сейчас он ровно один).
do $$
declare w record; n int; total int := 0;
begin
  for w in select id from worlds loop
    select seed_region_forts(w.id) into n;
    total := total + n;
    raise notice 'мир %: поставлено крепостей %', w.id, n;
  end loop;
  raise notice 'всего поставлено крепостей: % (шестнадцать на мир; 0 — уже стояли)', total;
end $$;

-- Крепости читаются клиентом тем же запросом, что лагеря и узлы
-- (map_cells_select_all из миграции 0001 уже открыт всем) — своей политики
-- не нужно. Писать в них будет только сервер, как и во всё остальное.
create index if not exists map_cells_regfort_idx
  on map_cells(world_id) where t = 'regfort';
