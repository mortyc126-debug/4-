-- =============================================================================
-- Разовая уборка уже существующих наложений в общем мире
-- =============================================================================
-- Автор с устройства: «миграции не произошло, старые точки как стояли
-- наложенные друг на друга, так и стоят» — и это правда. Разбор:
--
--   * thinMapDensity10 в index.html чистит W.map, то есть ОДИНОЧНУЮ игру.
--     В общем мире точки и лагеря — это строки map_cells в базе, никакая
--     клиентская миграция их не видит и видеть не может.
--   * Правка размещения (MIN_STRUCT_GAP=30 + запечённая маска настоящей воды
--     в mp-join/mp-tick) запрещает только НОВЫЕ наложения. То, что уже лежит
--     в таблице, она по определению не трогает.
--
-- Поэтому уборка — отдельное серверное событие overlap_cleanup
-- (applyOverlapCleanup в supabase/functions/mp-tick/index.js). ДЕПЛОЙ mp-tick
-- ОБЯЗАТЕЛЕН ДО выполнения SQL ниже, иначе тикер не будет знать новый тип
-- события и строка просто провисит необработанной.
--
-- Что удаляется: клетки в настоящей воде; клетки ближе 30 от ЗАМКА; из пары
-- клеток ближе 30 друг к другу — менее ценная (точка сбора ценнее лагеря).
-- Что не трогается: игроки/замки вообще, и клетка, в которую прямо сейчас
-- идёт чей-то поход (иначе отряд прибыл бы в пустоту).
--
-- Событие разовое: себя оно НЕ перепланирует (в отличие от ambient_seed).
-- Идемпотентно — повторный запуск ничего не добавит, пока предыдущая уборка
-- этого мира ещё числится в events.
insert into events (world_id, fire_at, type, data)
select w.id, now(), 'overlap_cleanup', '{}'::jsonb
from worlds w
where not exists (
  select 1 from events e where e.world_id = w.id and e.type = 'overlap_cleanup'
);

