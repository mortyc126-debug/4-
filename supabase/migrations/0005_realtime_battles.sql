-- Гонка конкурентных тиков. mp-tick сейчас выбирает необработанные события,
-- применяет их, и только ПОСЛЕ этого помечает processed=true — короткое
-- окно, где два параллельных запуска (pg_cron раз в 15с плюс запуск на
-- каждый опрос mp-join активным игроком, см. README) МОГУТ забрать одну и
-- ту же строку events дважды. Раньше (одноразовые события — постройка,
-- обучение, мгновенный бой одним вызовом) это было маловероятной царапиной:
-- окно гонки — доли секунды одного HTTP-вызова. Теперь бой размазан на
-- несколько последовательных событий type:'battle_round' с интервалом в
-- одну "клетку" пг_крона — то же самое окно гонки открывается заново на
-- КАЖДЫЙ раунд боя, а задвоенный раунд означает задвоенные потери/урон.
--
-- claimed_at — простая аренда без отдельной SQL-функции/транзакции:
-- mp-tick перед обработкой атомарно проставляет claimed_at=now() строке,
-- ГДЕ processed=false И (claimed_at IS NULL ИЛИ claimed_at старше 60с) —
-- один UPDATE ... WHERE ... с фильтром по claimed_at и есть атомарная
-- защита (конкурентный UPDATE той же строки просто не найдёт её в своём
-- WHERE, раз первый уже успел проставить свежий claimed_at), самоисцеляется
-- через 60с, если клеймившая функция упала посреди обработки, не оставляя
-- событие висеть навечно.
alter table events add column if not exists claimed_at timestamptz;

comment on column events.claimed_at is
  'Аренда обработки события — см. заголовок 0005_realtime_battles.sql. NULL или старше 60с = свободно для захвата.';
