-- "как если бы армии схлестнулись", с живыми полосками HP по ходу боя и
-- возможностью отступить, не дожидаясь исхода — подробности см.
-- supabase/functions/mp-tick/index.js (initPvpBattle/runPvpBattleRounds для
-- штурмов, initRaidBattle/runRaidBattleRounds — то же самое для рейдов).
--
-- Никаких новых таблиц не нужно: марш в бою — это marches.state='siege'
-- (столбец уже был в CHECK-свободном text-поле с самой первой миграции,
-- просто ни разу не выставлялся — 'go'|'gather'|'siege'|'back' были описаны
-- в комментарии 0001, но siege оставался мёртвым значением до сих пор),
-- само промежуточное состояние боя (текущий состав войск, полководцы,
-- дисциплина, HP-итоги для полосок) лежит в marches.data (jsonb), как и
-- прежде лежали dist/spd/carry.
--
-- Единственное реальное изменение схемы — events.claimed_at ниже.
