-- =============================================================================
-- Фаза 30 — гибель правителя и летопись павших.
-- =============================================================================
-- Снос города (Фаза 29, см. runDemolishRounds в mp-tick) доводит Ратушу до
-- нуля прочности — саму её снести нельзя, она не может пропасть с карты
-- города, но её обнуление и есть конец правления. Автор: "умер правитель и
-- всё, замка нет, и его тоже нет".
--
-- Почему НЕ удаляем строку игрока прямо в момент гибели, а помечаем
-- dead_at. Осада почти всегда заканчивается, пока проигравший офлайн (бой
-- считает pg_cron, браузер для этого не нужен вовсе). Если стереть его
-- сразу, при следующем заходе он увидит не экран гибели, а чистую форму
-- регистрации — как будто ничего не было и вся его партия просто исчезла
-- без объяснений. Поэтому строка живёт помеченной: с карты игрок пропадает
-- немедленно и для всех (см. фильтры dead_at is null в клиенте и функциях),
-- но сам он при следующем заходе получает честный экран "Правитель погиб" с
-- итогом правления. Физическое стирание — в момент, когда он сам нажмёт
-- "Заложить новую летопись" (Edge Function mp-restart).
alter table players add column if not exists dead_at timestamptz;

-- Живых в мире всегда меньше, чем строк накопится за его историю, а
-- спрашивают почти всегда именно живых (соседи, цели атаки, посев точек) —
-- частичный индекс ровно под этот вопрос.
create index if not exists players_alive_idx on players(world_id) where dead_at is null;

-- ---------------------------------------------------------------------------
-- Летопись. Пока — только записи о павших правителях (kind='fall'), но
-- таблица заведена как общий свод событий мира на будущее: автор прямо
-- сказал, что хрониками займёмся следующей задачей, и заводить под них
-- отдельную таблицу второй раз не хочется.
--
-- Ник НЕ удаляется вместе с игроком (прямое указание автора: "ник не удаляй...
-- поставь сохранения ника в хрониках. По типу «такой-то правитель был
-- уничтожен таким-то»") — здесь он и остаётся, уже отвязанный от строки
-- players, которая к тому моменту будет стёрта.
create table if not exists chronicles (
  id bigint generated always as identity primary key,
  world_id uuid not null references worlds(id) on delete cascade,
  kind text not null,                       -- пока только 'fall'
  nick text not null default '',            -- чьё правление кончилось
  race text not null default '',
  -- Кто, когда, где и с какой мощью. Отдельной колонкой не разносим: состав
  -- записи у разных kind будет разный, а читает её пока только экран гибели.
  data jsonb not null default '{}',
  created_at timestamptz not null default now()
);
create index if not exists chronicles_world_idx on chronicles(world_id, created_at desc);

-- Летопись открыта на чтение всем — она для того и ведётся. Записывает в
-- неё только mp-tick через service_role, у которого RLS не действует, так
-- что политики на запись нет вовсе: подделать запись о чужой гибели
-- напрямую через API нельзя.
alter table chronicles enable row level security;
drop policy if exists chronicles_select_all on chronicles;
create policy chronicles_select_all on chronicles for select
  using (true);
