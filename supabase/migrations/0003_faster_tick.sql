-- Автор пожаловался: очередь стройки/тренировки/боя показывается сразу
-- (mp-build/mp-train/mp-attack и т.д. пишут её мгновенно), но САМ результат
-- (новый уровень здания, исход боя) применяет только тикер (mp-tick) — а тот
-- раньше крутился раз в минуту (см. 0002_phase2_tick.sql). Даже 10-секундная
-- стройка ждала бы до минуты, чтобы это увидеть.
--
-- Решение — в ДВЕ части (см. supabase/README.md за подробным разбором):
--   1. mp-join/index.js теперь толкает тикер на КАЖДЫЙ свой вызов (а его же
--      клиент опрашивает раз в 5с, см. mpRefreshPlayer() в index.html) —
--      собственные постройки/бои игрока применяются в течение тех же 5с,
--      НЕ дожидаясь общего расписания. Правка уже в самой Edge Function,
--      этот SQL её не трогает — нужен только повторный деплой mp-join.
--   2. Этот файл — общий pg_cron ускорен с раз-в-минуту до раз-в-15с, для
--      случаев, когда НИКТО активно не опрашивает (например, вас атакуют,
--      пока вы не в игре — тикер обязан сам довести бой до конца, дожидаться
--      некого). 15с — компромисс: не "раз в секунду" (это 60 запросов/мин =
--      ~2.6 млн/месяц, риск упереться в лимит бесплатных вызовов Edge
--      Functions), а 4 запроса/мин = ~172800/мес — с большим запасом.
--
-- ПЕРЕД тем как выполнять: mp-join нужно передеплоить (см. supabase/functions/
-- mp-join/index.js — тот же способ, что и раньше: Dashboard → Edge Functions,
-- либо `supabase functions deploy mp-join`). Секрет MP_TICK_SECRET уже
-- задан (он общий на все функции, см. 0002) — новых секретов заводить не
-- нужно, mp-join читает тот же самый.
--
-- ВАЖНО про синтаксис ниже: cron.schedule с интервалом в секундах ('15
-- seconds' вместо 5-польного cron-выражения) поддерживается pg_cron начиная
-- с версии 1.4+. Проверить версию: select extversion from pg_extension
-- where extname='pg_cron'; Supabase обычно держит актуальную версию, но если
-- этот SQL упадёт с ошибкой синтаксиса расписания — раскомментируйте
-- запасной вариант ниже (обычное cron-выражение, минимум раз в минуту, это
-- ограничение самого 5-польного формата, не Supabase).
select cron.unschedule(jobid) from cron.job where jobname = 'mp-tick-every-minute';
select cron.unschedule(jobid) from cron.job where jobname = 'mp-tick-fast';

select cron.schedule(
  'mp-tick-fast',
  '15 seconds', -- pg_cron 1.4+; при ошибке синтаксиса см. запасной вариант в комментарии ниже
  $$
  select net.http_post(
    url := 'https://xzuwqgpwzlmpglnuijio.supabase.co/functions/v1/mp-tick',
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-tick-secret', 'REPLACE_WITH_SECRET'
    ),
    body := '{}'::jsonb
  );
  $$
);

