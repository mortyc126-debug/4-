-- =============================================================================
-- Фаза 31 — мощь державы на сервере.
-- =============================================================================
-- Колонка players.power существует с самой первой миграции, но никогда не
-- заполнялась: мощь считалась только в браузере (power()/mpPower() в
-- index.html), а сервер о ней не знал вовсе. Автор: "будут рейтинги в том
-- числе и по мощи" — значит число должно принадлежать серверу, а не клиенту,
-- который мог бы назвать любое.
--
-- Схему менять почти не нужно: колонка уже есть и уже bigint (мощь развитой
-- державы — сотни миллионов, в int не поместилась бы). Считать её начинают
-- mp-join (на каждом пятисекундном опросе игрока) и mp-tick (в конце боя, где
-- она меняется сильнее всего) — см. applyPower там же. Высшая мощь за всё
-- правление копится отдельно, в state.peakPower: текущая на момент гибели
-- всегда занижена, у павшего к той секунде нет ни войск, ни половины города.
--
-- Здесь — только индекс под сам рейтинг: живые игроки одного мира по
-- убыванию мощи. Частичный (dead_at is null, см. миграцию 0007) — павшие в
-- таблице ещё какое-то время лежат, но в рейтинге им не место.
create index if not exists players_power_idx
  on players(world_id, power desc)
  where dead_at is null;
