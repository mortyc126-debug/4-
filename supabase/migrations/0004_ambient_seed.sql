-- Фаза 15, продолжение — фоновый respawn точек/лагерей (не по истощению)
-- =============================================================================
-- Автор попросил: respawn точек/лагерей срабатывал раньше ТОЛЬКО когда
-- кто-то выбирал старую точку до дна/разгромил лагерь (Фаза 8, кусочек 3,
-- см. applyNodeRespawn/applyCampRespawn в mp-tick) — территория, до которой
-- ещё никто не добрался, точек не получала вовсе. Теперь есть отдельная
-- самоподдерживающаяся цепочка событий (type:"ambient_seed",
-- applyAmbientSeed в supabase/functions/mp-tick/index.js — деплой ЭТОЙ
-- функции обязателен ДО выполнения SQL ниже, иначе тикер не будет знать
-- новый тип события), которая сама подсевает небольшими порциями по
-- расписанию (раз в 10 минут, 2 точки + 1 лагерь за раз), с потолком,
-- пропорциональным числу игроков (не даёт карте переполниться) — подробный
-- разбор чисел и защит от нагрузки на сервер см. supabase/README.md.
--
-- Новым мирам это заводит сам mp-join (см. правку в mp-join/index.js) —
-- этот файл нужен ТОЛЬКО чтобы завести цепочку для мира, который уже
-- существовал ДО этой правки (обычный случай — у вас уже есть игроки).
--
-- Идемпотентно — если выполнить дважды, второй раз просто ничего не
-- добавит (проверяет, что цепочка для мира ещё не запущена: НИ ОДНОГО
-- события ambient_seed, обработанного ИЛИ ожидающего, ещё не было).
insert into events (world_id, fire_at, type, data)
select w.id, now(), 'ambient_seed', '{}'::jsonb
from worlds w
where not exists (
  select 1 from events e where e.world_id = w.id and e.type = 'ambient_seed'
);

