-- =============================================================================
-- Фаза 58 — строка игрока: ни править её напрямую, ни читать чужую.
-- =============================================================================
-- Три дыры в одной таблице, все три — в обход edge-функций, прямо anon-ключом
-- из консоли браузера.
--
-- 1. players_update_self (миграция 0001) разрешала игроку UPDATE своей строки
--    целиком: state со складом и войсками, power, rating, shield_until. Одной
--    строкой в консоли можно было выдать себе миллион золота. Клиенту эта
--    политика не нужна вовсе: он не пишет в players ни разу, все изменения
--    идут через функции под service-role, на которую RLS не действует.
--    mail_update_own — то же самое для почты: клиент помечает письма
--    прочитанными у себя (localStorage), а не в базе, и политика лишь позволяла
--    переписать собственные боевые отчёты.
--
-- 2. players_select_world открывает строки всех игроков мира — так и задумано
--    (карта, соседи, таблицы мира). Но вместе со строкой открывался и state:
--    точный состав войск, склад, снаряжение любого соседа одним запросом. То
--    есть разведка, ради которой в игре есть лазутчики и донесения, обходилась
--    целиком. Строки остаются открыты, колонка state — нет: её читают только
--    функции. Из state клиенту правда нужны два числа — ратуша и полководец
--    соседа, — их теперь отдают вычисляемые колонки hall_now и gen_id.
--
-- 3. Ник. mp-join клал его как есть, и ник с разметкой исполнялся в браузере
--    того, кто открыл письмо о бое или панель чужого отряда. Клиент теперь
--    экранирует ник при выводе, mp-join отсекает опасные символы на входе, а
--    здесь чистятся ники, заведённые до этого.
--
-- ВАЖНО о порядке выкладки. Клиент (index.html) с этой фазы читает hall_now и
-- gen_id, а если колонок нет — сам откатывается на прежнюю выборку из state.
-- Поэтому порядок такой: сначала выкатить сайт, затем накатить эту миграцию.
-- Наоборот — старый клиент, у которого отнят state, перестанет видеть соседей
-- до выкладки нового.
--
-- ВАЖНО на будущее. Права на чтение players теперь выдаются поколоночно (см.
-- блок do ниже). Новая колонка, добавленная следующими миграциями, клиенту
-- НЕ видна, пока её явно не открыть:
--   grant select (имя_колонки) on public.players to anon, authenticated;
--
-- Как применить: Supabase Dashboard -> SQL Editor -> вставить целиком -> Run.

-- 1. Прямая запись — закрыта.
drop policy if exists players_update_self on players;
drop policy if exists mail_update_own on mail;

-- 2. Две вычисляемые колонки вместо чтения state. Тип проверяется: если в
-- state лежит не число, колонка просто пустая — клиент и раньше превращал
-- нечисловое значение в «ратуша 1» / «полководец по умолчанию».
alter table players add column if not exists hall_now int generated always as (
  case when jsonb_typeof(state->'b'->'hall') = 'number'
       then (state->'b'->>'hall')::numeric::int end
) stored;
alter table players add column if not exists gen_id int generated always as (
  case when jsonb_typeof(state->'gen'->'id') = 'number'
       then (state->'gen'->>'id')::numeric::int end
) stored;

-- Чтение: всё, кроме state. Список колонок берётся из самой таблицы, а не
-- переписывается руками — в живой базе могут быть колонки, заведённые через
-- дашборд мимо миграций, и клиент мог на них опираться. auth_uid остаётся
-- открытым сознательно: на нём стоят политики почты, союзов и чата
-- (подзапрос "select id from players where auth_uid = auth.uid()" выполняется
-- с правами читающего).
revoke select on players from anon, authenticated;
do $$
declare cols text;
begin
  select string_agg(quote_ident(column_name), ', ' order by ordinal_position)
    into cols
    from information_schema.columns
   where table_schema = 'public' and table_name = 'players' and column_name <> 'state';
  execute format('grant select (%s) on public.players to anon, authenticated', cols);
end $$;

-- 3. Ники, заведённые до фильтра в mp-join: те же символы, что отсекает он.
update players
   set nick = btrim(regexp_replace(nick, '[<>&"''`[:cntrl:]]', '', 'g'))
 where nick ~ '[<>&"''`[:cntrl:]]';
