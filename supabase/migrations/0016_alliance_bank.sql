-- =============================================================================
-- Фаза 55 — казна союза и стройка крепости альянса.
-- =============================================================================
-- Автор: «строительство крепости альянса, то есть скорость возведения зависит
-- от количества участников и ресурсов (ресурсы можно жертвовать альянсу, а
-- жертвует ресурсы игроки)... вместимость крепости 2 миллиона, а сбора
-- максимум тоже 2 миллиона, но сбор нужно прокачать, а вместимость крепости
-- сразу по дефолту такая и по идее неизменная». И раньше: «мало просто
-- уничтожить, нужно ещё и свою крепость построить... это место, где
-- расположена крепость варваров, отмечено, и на нём можно возвести крепость
-- альянса после разрушения крепости варваров».
--
-- Схемы тут почти нет, и это нарочно:
--
-- 1. КАЗНА — четыре числа, и живут они прямо в строке союза (alliances.res),
--    как ресурсы игрока живут в players.state. Отдельная таблица «казна»
--    завела бы строку-на-союз с теми же четырьмя числами и обязанностью
--    следить, что она вообще существует, — ровно то, ради чего таблицы и не
--    заводят.
--
-- 2. СТРОЙКА идёт в самой клетке (map_cells.data), а не в новой таблице:
--    место стройки — та же самая клетка t='regfort', что была крепостью
--    варваров (миграция 0013), и весь клиент, карта и наведение маршей уже
--    умеют её читать. Отдельная таблица «стройки» означала бы вторую
--    сущность на то же место и вечный вопрос, какая из двух права.
--    Появляются два состояния и три поля в data:
--      state:'building' — идёт стройка; build_t0/build_t1 — её срок,
--                         build_cost — сколько за неё уже отдано казной
--                         (нужно для «помочь»: доля от стоимости = доля
--                         снятого времени);
--      state:'ally'     — крепость стоит, alliance_id — чья.
--    Крепость альянса УРОВНЕЙ НЕ ИМЕЕТ (прямое условие автора: «там нет
--    уровней, они не как лагеря варваров, это нечто уникальное, как
--    святыня»), поэтому ни поля уровня, ни таблицы улучшений тут нет и не
--    будет.
--
-- Как применить: Supabase Dashboard -> SQL Editor -> вставить целиком -> Run.

-- Казна союза. Янтарь сюда НЕ входит: он личная валюта (магазин, основание
-- союза), и складывать его в общий котёл автор не просил.
alter table alliances
  add column if not exists res jsonb not null
  default '{"food":0,"wood":0,"stone":0,"gold":0}'::jsonb;

-- Сколько этот соратник отдал в казну за всё время. Нужно не для механики, а
-- для того, чтобы союз это ВИДЕЛ: без такой строки жертвуют единицы, а
-- пользуются все.
alter table alliance_members
  add column if not exists donated bigint not null default 0;

-- Старым союзам (заведённым до этой миграции) поле res досталось бы NULL,
-- если бы кто-то создал строку в тот же миг — default покрывает только новые.
-- Повторный запуск безвреден.
update alliances set res = '{"food":0,"wood":0,"stone":0,"gold":0}'::jsonb where res is null;
